# Body of a LaTeX tabular.  The final row must NOT end with "\\" (a row
# terminator right before an \input file boundary breaks the alignment);
# main.tex supplies the last "\\" itself.
write_rows <- function(rows, file) {
  n <- length(rows)
  rows[n] <- sub("\\\\\\\\\\s*$", "", rows[n])
  # typographic minus for negative numbers (not inside math, not in ranges like "1--2")
  rows <- gsub("(?<![A-Za-z0-9$\\-])-(?=\\.?[0-9])", "$-$", rows, perl = TRUE)
  writeLines(rows, file.path(TABS, paste0(file, ".tex")))
  message("wrote tables/", file, ".tex")
}

