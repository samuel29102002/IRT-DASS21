find_root <- function(path = getwd()) {
  p <- normalizePath(path)
  repeat {
    if (file.exists(file.path(p, "data", "DASS.xlsx"))) return(p)
    parent <- dirname(p)
    if (identical(parent, p))
      stop("Project root (folder with data/DASS.xlsx) not found above ", path)
    p <- parent
  }
}
