# robust fit measures from a lavaan WLSMV fit
fitm <- function(fit) {
  w <- c("chisq.scaled", "df", "pvalue.scaled", "cfi.scaled", "tli.scaled",
         "rmsea.scaled", "rmsea.ci.lower.scaled", "rmsea.ci.upper.scaled", "srmr")
  out <- tryCatch(lavaan::fitMeasures(fit, w), error = function(e) NULL)
  if (is.null(out)) out <- lavaan::fitMeasures(
    fit, c("chisq", "df", "pvalue", "cfi", "tli", "rmsea",
           "rmsea.ci.lower", "rmsea.ci.upper", "srmr"))
  setNames(as.numeric(out), c("chisq", "df", "pvalue", "cfi", "tli", "rmsea",
                              "rmsea.lo", "rmsea.hi", "srmr"))
}

## ---------------------------------------------------------------- 6. logging
# log_open("01") mirrors all console output to results/logs/step_01.txt.
# check() prints a value next to the reference value from the independent
# Python implementation, so discrepancies are visible immediately.
IN_KNITR <- function() isTRUE(getOption("knitr.in.progress"))
log_open <- function(step) {
  f <- file.path(LOGS, sprintf("step_%s.txt", step))
  .CHECKS$n <- 0; .CHECKS$fail <- 0
  # When knitting, the HTML/Markdown report is the log; sink() would break knitr.
  if (!IN_KNITR()) { while (sink.number() > 0) sink(); sink(f, split = TRUE) }
  cat("=================================================================\n")
  cat(sprintf(" STEP %s   run at %s\n", step, format(Sys.time(), "%Y-%m-%d %H:%M:%S")))
  cat(sprintf(" R %s | %s\n", getRversion(), R.version$platform))
  cat("=================================================================\n\n")
  invisible(f)
}
log_close <- function() {
  cat("\n--- end of log ---\n")
  if (!IN_KNITR()) { while (sink.number() > 0) sink(); message("Log written to results/logs/") }
}
section <- function(title) cat("\n----", title, paste(rep("-", max(3, 60 - nchar(title))), collapse = ""), "\n")

.CHECKS <- new.env(parent = emptyenv()); .CHECKS$n <- 0; .CHECKS$fail <- 0
check <- function(label, value, reference, tol = 0) {
  ok <- if (is.numeric(value) && is.numeric(reference))
    isTRUE(all(abs(value - reference) <= tol + 1e-12)) else identical(as.character(value), as.character(reference))
  .CHECKS$n <- .CHECKS$n + 1; if (!ok) .CHECKS$fail <- .CHECKS$fail + 1
  fmt <- function(x) if (is.numeric(x)) paste(signif(x, 6), collapse = ", ") else paste(x, collapse = ", ")
  cat(sprintf("  [%s] %-42s R = %-18s ref = %-14s tol = %s\n",
              if (ok) " OK " else "DIFF", label, fmt(value), fmt(reference), tol))
  invisible(ok)
}
check_summary <- function() {
  cat(sprintf("\n  CHECKS: %d run, %d OK, %d DIFF\n", .CHECKS$n,
              .CHECKS$n - .CHECKS$fail, .CHECKS$fail))
}

