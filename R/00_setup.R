## ---------------------------------------------------------------- 4. number store
# Every number quoted in the essay passes through num().  The store is saved to
# results/numbers.rds after each call, so it survives when the steps are run in
# separate sessions; write_numbers() turns it into essay/numbers.tex.
NUM_FILE <- file.path(RES, "numbers.rds")
.NUMBERS <- new.env(parent = emptyenv())
.NUMBERS$vals <- if (file.exists(NUM_FILE)) readRDS(NUM_FILE) else list()

num <- function(name, value) {
  if (!grepl("^[A-Za-z]+$", name)) stop("LaTeX macro names may contain letters only: ", name)
  .NUMBERS$vals[[name]] <- as.character(value)
  saveRDS(.NUMBERS$vals, NUM_FILE)
  invisible(value)
}

write_numbers <- function(path = file.path(ESSAY, "numbers.tex")) {
  v <- .NUMBERS$vals[order(names(.NUMBERS$vals))]
  lines <- sprintf("\\newcommand{\\%s}{%s}", names(v), unlist(v))
  writeLines(c("% Auto-generated by the R pipeline -- do not edit by hand.", lines), path)
  message("numbers.tex written with ", length(lines), " macros")
}

